import assert from 'node:assert/strict'
import { test } from 'node:test'
import { chromium } from 'playwright-core'

test('benchmark and synthetic officer workflow stay separate', { timeout: 90_000 }, async () => {
  const origin = process.env.COBI_E2E_URL
  assert.ok(origin, 'Set COBI_E2E_URL to an isolated frontend with a disposable SQLite database')
  const browser = await chromium.launch(process.env.COBI_E2E_CHROME
    ? { executablePath: process.env.COBI_E2E_CHROME }
    : { channel: 'chrome' })
  try {
    const page = await browser.newPage({ baseURL: origin, viewport: { width: 1440, height: 1020 }, acceptDownloads: true })
    const jsErrors = []
    page.on('pageerror', error => jsErrors.push(error.message))
    const nav = label => page.getByRole('navigation').getByRole('button', { name: label, exact: true })
    await page.goto(origin)
    await nav('Research Lab').click()
    await page.getByRole('heading', { name: 'Final probability metrics' }).waitFor()
    assert.match(await page.getByText('PUBLIC_DATA_BENCHMARKED').innerText(), /PUBLIC_DATA_BENCHMARKED/)
    await page.getByRole('button', { name: 'mlp-b128' }).click()
    await page.getByRole('img', { name: 'Train and validation log loss for mlp-b128' }).waitFor()
    const reliability = page.getByRole('img', { name: /Raw and calibrated reliability/ })
    await reliability.waitFor()
    await page.waitForFunction(() => document.querySelector('.research-plot[src]')?.naturalWidth > 0)
    const downloaded = page.waitForEvent('download')
    await page.getByRole('link', { name: 'model_manifest.json' }).click()
    assert.equal((await downloaded).suggestedFilename(), 'model_manifest.json')

    await nav('AI Assessment').click()
    const detail = await page.request.get('/api/applications/DEMO-001')
    const baseline = await detail.json()
    assert.equal(baseline.assessment.affordability.pmt_vnd, 1_250_000)
    await page.getByText('Checkout PD and expected loss require bank validation.', { exact: false }).waitFor()
    await page.getByText('Evidence AI · shadow only', { exact: true }).waitFor()
    const shadow = await (await page.request.get('/api/evidence-ai/shadow/DEMO-001')).json()
    assert.equal(shadow.status, 'EVIDENCE_AI_VALIDATION_BLOCKED')
    assert.equal(shadow.material_error_probability, null)
    await page.getByRole('button', { name: 'Open evidence research' }).click()
    await page.getByRole('heading', { name: 'Evidence AI Research', exact: true }).waitFor()
    await page.getByRole('heading', { name: 'Semantic-aware validation', exact: true }).waitFor()
    await page.getByText('POST UNBLINDING EXPLORATORY').waitFor()
    await page.getByText('NOT_EVALUATED', { exact: true }).waitFor()
    await page.getByRole('img', { name: /figure1 generator c performance/ }).waitFor()
    await page.getByRole('button', { name: 'Deep Sets', exact: true }).waitFor()
    await page.getByRole('heading', { name: 'Suspected field errors' }).waitFor()
    await page.getByRole('img', { name: /Observed defect rate/ }).waitFor()
    await page.getByText(/Exact field F1 0\.626/).waitFor()
    await nav('What-if Simulator').click()
    await page.getByRole('checkbox', { name: 'Check UCI benchmark compatibility' }).check()
    await page.getByRole('button', { name: 'Run scenario' }).click()
    await page.getByRole('status').filter({ hasText: 'PD_UNAVAILABLE_SCHEMA_MISMATCH' }).waitFor()
    assert.deepEqual((await (await page.request.get('/api/applications/DEMO-001')).json()).assessment, baseline.assessment)

    await nav('Applications').click()
    await page.getByRole('button', { name: 'New synthetic case' }).click()
    await page.getByLabel('Applicant label').fill('Synthetic E2E fixture')
    await page.getByRole('button', { name: 'Add to case queue' }).click()
    await page.getByText('Synthetic application added to the local case queue.').waitFor()
    await nav('Officer Review').click()
    await page.getByRole('button', { name: /Confirm review path/ }).click()
    await page.getByRole('textbox', { name: /Reason for this action/ }).fill('Reviewed the synthetic checkout evidence.')
    await page.getByRole('button', { name: 'Record review action' }).click()
    await page.getByText('Reviewed the synthetic checkout evidence.', { exact: true }).waitFor()
    await page.getByRole('button', { name: /Record consent withdrawal/ }).click()
    await page.getByRole('textbox', { name: /Reason for this action/ }).fill('Synthetic applicant withdrew consent.')
    await page.getByRole('button', { name: 'Record review action' }).click()
    await page.getByText('Synthetic applicant withdrew consent.', { exact: true }).waitFor()
    await nav('AI Assessment').click()
    await page.getByRole('heading', { name: 'Mandatory checks need attention' }).waitFor()
    assert.deepEqual(jsErrors, [])

    await page.setViewportSize({ width: 390, height: 844 })
    await page.getByRole('button', { name: 'Open menu' }).click()
    await nav('Research Lab').click()
    await page.getByRole('heading', { name: 'Research Lab' }).waitFor()
    await page.getByRole('heading', { name: 'Final probability metrics' }).waitFor()
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth))
    await page.getByRole('button', { name: 'Open menu' }).click()
    await nav('Evidence AI Research').click()
    await page.getByRole('heading', { name: 'Evidence AI Research', exact: true }).waitFor()
    await page.getByRole('heading', { name: 'Semantic-aware validation', exact: true }).waitFor()
    await page.getByRole('button', { name: 'Deep Sets', exact: true }).waitFor()
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth))
    if (process.env.COBI_E2E_SCREENSHOT) await page.screenshot({ path: process.env.COBI_E2E_SCREENSHOT })
  } finally {
    await browser.close()
  }
})
